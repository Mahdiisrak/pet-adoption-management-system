-- Owner directory lookup with explicit NO_DATA_FOUND handling for empty results.
CREATE OR REPLACE PROCEDURE PR_OWNER_DIRECTORY(
  P_SEARCH VARCHAR2,
  P_MESSAGE OUT VARCHAR2,
  P_ROWS OUT SYS_REFCURSOR
)
AS
  V_MATCH_COUNT NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_MATCH_COUNT
  FROM OWNER o JOIN PERSON p ON p.PERSON_ID=o.PERSON_ID
  WHERE P_SEARCH IS NULL
     OR UPPER(o.PERSON_ID)=UPPER(P_SEARCH)
     OR UPPER(TRIM(p.FIRST_NAME||' '||p.LAST_NAME))=UPPER(P_SEARCH)
     OR UPPER(p.FIRST_NAME)=UPPER(P_SEARCH)
     OR UPPER(p.LAST_NAME)=UPPER(P_SEARCH)
     OR EXISTS (
       SELECT 1 FROM PERSON_PHONE pp
       WHERE pp.PERSON_ID=o.PERSON_ID AND pp.PHONE=P_SEARCH
     );

  IF V_MATCH_COUNT=0 THEN
    RAISE NO_DATA_FOUND;
  END IF;

  P_MESSAGE:='Owner records found';
  OPEN P_ROWS FOR
    SELECT o.PERSON_ID OWNER_ID,p.FIRST_NAME||' '||p.LAST_NAME OWNER_NAME,
      o.OCCUPATION,(SELECT MIN(pp.PHONE) FROM PERSON_PHONE pp WHERE pp.PERSON_ID=o.PERSON_ID) PHONE,
      pet.PET_ID,pet.NAME PET_NAME,pet.SPECIES,pet.BREED,
      TO_CHAR(gp.CHECK_IN_DATE,'YYYY-MM-DD') CHECK_IN_DATE,gp.RELEVANT_TIME
    FROM OWNER o JOIN PERSON p ON p.PERSON_ID=o.PERSON_ID
    LEFT JOIN GUEST_PET_OWNER gpo ON gpo.OWNER_ID=o.PERSON_ID
    LEFT JOIN GUEST_PET gp ON gp.PET_ID=gpo.PET_ID
    LEFT JOIN PET pet ON pet.PET_ID=gp.PET_ID
