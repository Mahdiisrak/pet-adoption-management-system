-- Explicit Cursor: counts all pets and available local pets.
CREATE OR REPLACE PROCEDURE PR_CURSOR_PET_SUMMARY(P_TOTAL OUT NUMBER,P_AVAILABLE OUT NUMBER)
AS
  CURSOR C_PETS IS
    SELECT p.PET_ID,l.ADOPTION_STATUS FROM PET p LEFT JOIN LOCAL_PET l ON l.PET_ID=p.PET_ID;
  V_PET C_PETS%ROWTYPE;
BEGIN
  P_TOTAL:=0;
  P_AVAILABLE:=0;
  OPEN C_PETS;
  LOOP
    FETCH C_PETS INTO V_PET;
    EXIT WHEN C_PETS%NOTFOUND;
    P_TOTAL:=P_TOTAL+1;
    IF V_PET.ADOPTION_STATUS='AVAILABLE' THEN P_AVAILABLE:=P_AVAILABLE+1; END IF;
  END LOOP;
  CLOSE C_PETS;
END;
/

