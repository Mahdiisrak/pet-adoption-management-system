-- COMMON TABLE EXPRESSION (WITH clause): employee adoption workload.
-- This same Oracle query is executed from PetCare Insights in the frontend.
WITH EMPLOYEE_CASES AS (
  SELECT e.PERSON_ID,
         p.FIRST_NAME||' '||p.LAST_NAME EMPLOYEE_NAME,
         COUNT(ap.ADOPTION_ID) ASSIGNED_CASES,
         SUM(CASE WHEN ap.STATUS='APPROVED' THEN 1 ELSE 0 END) ACTIVE_CASES,
         SUM(CASE WHEN ap.STATUS='ADOPTED' THEN 1 ELSE 0 END) ADOPTED_CASES
  FROM EMPLOYEE e
  JOIN PERSON p ON p.PERSON_ID=e.PERSON_ID
  LEFT JOIN ADOPTION_PROCESS ap ON ap.EMPLOYEE_ID=e.PERSON_ID
  GROUP BY e.PERSON_ID,p.FIRST_NAME,p.LAST_NAME
), RANKED_CASES AS (
  SELECT ec.*,
         DENSE_RANK() OVER (ORDER BY ec.ASSIGNED_CASES DESC) WORKLOAD_RANK
  FROM EMPLOYEE_CASES ec
)
SELECT PERSON_ID,EMPLOYEE_NAME,ASSIGNED_CASES,ACTIVE_CASES,ADOPTED_CASES,WORKLOAD_RANK
FROM RANKED_CASES
ORDER BY WORKLOAD_RANK,EMPLOYEE_NAME;

